/**
 * Data structures for Multi-Track Dialogue Studio
 */

export type GeminiVoiceName = 'Puck' | 'Charon' | 'Kore' | 'Fenrir' | 'Zephyr' | 'Aoede';

export type FillerIntensity = 'subtle' | 'moderate' | 'dramatic';

export type AmbientDensity = 'none' | 'low' | 'medium' | 'high';

export type ReactionType = 'chuckle' | 'giggle' | 'sniff' | 'cough' | 'paper_shuffle' | 'sigh';

export interface ReactionHook {
  id: string;
  triggerSpeakerId: string; // The speaker reacting during another speaker's turn / pause
  reactionType: ReactionType;
  offsetMs: number;         // Offset into the silence interval
  intensity: number;        // 0.1 to 1.0 volume scale
  reason?: string;          // e.g. "Reacting to Goblin's boast"
  autoDetected?: boolean;   // Flagged if generated by automated humor analyzer
}

export interface SpeakerProfile {
  id: string;
  name: string;
  voiceName: GeminiVoiceName;
  stylePrompt: string; // Tone guidance for Gemini TTS (e.g. "Battle-ready warrior, enthusiastic and urgent")
  color: string;       // Distinct theme color for channel strip & waveforms
  avatarIcon?: string;
  gender?: 'neutral' | 'masculine' | 'feminine';
  savedPersonaId?: string; // Reference to saved persona if applied
}

export interface SavedVoicePersona {
  id: string;
  name: string;             // Base name or deduplicated name e.g. "DM", "DM-2", "DM-3"
  voiceName: GeminiVoiceName;
  stylePrompt: string;
  color: string;
  tags?: string[];
  createdAt: number;
  lastUsedAt: number;
}

export interface DialogueLine {
  id: string;
  speakerId: string;
  rawText: string;
  enhancedText: string;
  isEnhanced: boolean;
  pauseAfterMs?: number; // Custom pause after this line (default ~400ms)
  reactionHook?: ReactionHook; // Optional ambient reaction in the following silence
}

export interface IgnoredLineDetail {
  lineNum: number;
  content: string;
  reason: 'comment' | 'stage_direction' | 'scene_header' | 'blank' | 'timestamp' | 'non_speaking';
  description: string;
}

export interface SpeakerValidationFlag {
  speakerName: string;
  isValidSpeaker: boolean;
  confidence: number;
  reason: string;
  suggestedAction: 'keep' | 'omit' | 'reassign';
  suggestedTarget?: string;
}

export interface SpeakerLineCount {
  speakerName: string;
  speakerId: string;
  lineCount: number;
  sampleUtterance: string;
  matchedPersona?: SavedVoicePersona;
  llmValidation?: SpeakerValidationFlag;
  isExcluded?: boolean;
  excludeAction?: 'omit' | 'reassign';
  reassignedToSpeakerName?: string;
}

export interface TranscriptValidationResult {
  fileName?: string;
  totalRawLines: number;
  speakingLinesCount: number;
  ignoredLinesCount: number;
  uniqueSpeakersCount: number;
  speakersSummary: SpeakerLineCount[];
  ignoredLines: IgnoredLineDetail[];
  parsedLines: {
    speakerName: string;
    text: string;
    lineNum: number;
  }[];
  summarySentence: string; // Exact format: "The transcript has 3 unique speakers: DM (42 lines), Maiah (37), and Anton (15). 30 lines are ignored because they are comments or other non-speaking lines."
  warnings: string[];
  hasLlmValidated?: boolean;
}

export interface AmbientConfig {
  density: AmbientDensity;
  enabledSounds: {
    paperShuffle: boolean;
    sniff: boolean;
    cough: boolean;
    chuckle: boolean;
    giggle: boolean;
    sigh: boolean;
  };
  volumeGain: number; // Volume multiplier (default 0.15 = ~ -16dB)
}

export interface AudioSegmentMarker {
  speakerId: string;
  speakerName: string;
  startSec: number;
  endSec: number;
  text: string;
  isSpeech: boolean;       // true = dialogue, false = silence pad
  ambientEvent?: string;   // e.g. "paper_shuffle" or "soft_chuckle"
  color: string;
}

export interface RenderedAudioStem {
  speakerId: string;
  speakerName: string;
  audioBase64: string;     // Base64 MP3 or WAV
  audioUrl: string;        // Playable blob URL
  durationSec: number;     // Matches all other stems down to the millisecond
  format: 'mp3' | 'wav';
  segments: AudioSegmentMarker[];
}

export interface DialogueProject {
  id: string;
  title: string;
  interSpeakerGapSec: number; // Default 0.4s
  fillerIntensity: FillerIntensity;
  ambientConfig: AmbientConfig;
  speakers: SpeakerProfile[];
  lines: DialogueLine[];
  masterAudioBase64?: string;
  masterAudioUrl?: string;
  totalDurationSec?: number;
  stems: RenderedAudioStem[];
  isGenerating?: boolean;
}
